CORE_RADIUS = 34.0
BELTS = [  # radius, width, tilt axis, tilt degrees, U direction (+1 / -1: the film runs opposite ways)
    (44.0, 14.0, (1.0, 0.0, 0.0), 32.0, 1.0),
    (47.0, 14.0, (0.0, 1.0, 0.0), -32.0, -1.0),
]
BELT_THICKNESS = 1.6
FRAMES_PER_BELT = 8
SPARKLE_R = 45.5  # tips stay inside the 100 cm envelope
SPARKLES = [((0.0, 0.0, SPARKLE_R), 0.00), ((0.0, 0.0, -SPARKLE_R), 0.50), ((SPARKLE_R, 0.0, 0.0), 0.17),
            ((-SPARKLE_R, 0.0, 0.0), 0.67), ((0.0, SPARKLE_R, 0.0), 0.33), ((0.0, -SPARKLE_R, 0.0), 0.83)]
SPARKLE_SIZE = 2.4


def rotate(v, axis, deg):
    # Rodrigues rotation of v about a unit axis.
    a = math.radians(deg)
    c, s = math.cos(a), math.sin(a)
    ax, ay, az = axis
    x, y, z = v
    dot = ax * x + ay * y + az * z
    cx, cy, cz = ay * z - az * y, az * x - ax * z, ax * y - ay * x
    return (x * c + cx * s + ax * dot * (1 - c), y * c + cy * s + ay * dot * (1 - c), z * c + cz * s + az * dot * (1 - c))


class Obj:
    def __init__(self):
        self.v, self.vt, self.vn, self.f = [], [], [], []

    def vert(self, p, uv, n):
        self.v.append(p)
        self.vt.append(uv)
        self.vn.append(n)
        return len(self.v)  # OBJ indices are 1-based; one v/vt/vn triple per corner keeps the indexing simple

    def tri(self, a, b, c):
        self.f.append((a, b, c))

    def quad(self, a, b, c, d):
        self.tri(a, b, c)
        self.tri(a, c, d)

    def write(self, path):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as fh:
            fh.write("# MegaJam26 #108 movie magic orb, generated by Scripts/build_issue108_orb.py\n")
            for p in self.v:
                fh.write("v %.4f %.4f %.4f\n" % p)
            for uv in self.vt:
                fh.write("vt %.5f %.5f\n" % uv)
            for n in self.vn:
                fh.write("vn %.5f %.5f %.5f\n" % n)
            fh.write("g Orb\ns 1\n")
            for a, b, c in self.f:
                fh.write("f %d/%d/%d %d/%d/%d %d/%d/%d\n" % (a, a, a, b, b, b, c, c, c))


def build_core(o, segs=40, rings=24):
    grid = []
    for j in range(rings + 1):
        lat = math.pi * j / rings - math.pi / 2
        row = []
        for i in range(segs + 1):
            lon = 2 * math.pi * i / segs
            n = (math.cos(lat) * math.cos(lon), math.cos(lat) * math.sin(lon), math.sin(lat))
            p = tuple(CORE_RADIUS * k for k in n)
            row.append(o.vert(p, (i / segs, j / rings), n))
        grid.append(row)
    for j in range(rings):
        for i in range(segs):
            # Counter-clockwise seen from outside.
            o.quad(grid[j][i], grid[j][i + 1], grid[j + 1][i + 1], grid[j + 1][i])


def build_belt(o, radius, width, axis, deg, direction, segs=96):
    def xf(p):
        return rotate(p, axis, deg)

    r_out, r_in = radius, radius - BELT_THICKNESS
    h = width / 2
    cols = {k: [] for k in ("out_lo", "out_hi", "in_lo", "in_hi", "el_lo", "el_hi", "eh_lo", "eh_hi")}
    for i in range(segs + 1):
        t = 2 * math.pi * i / segs
        c, s = math.cos(t), math.sin(t)
        radial = xf((c, s, 0.0))
        up = xf((0.0, 0.0, 1.0))
        down = (-up[0], -up[1], -up[2])
        inward = (-radial[0], -radial[1], -radial[2])
        u = 10.0 + (FRAMES_PER_BELT * i / segs if direction > 0 else FRAMES_PER_BELT * (1 - i / segs))
        po_lo, po_hi = xf((r_out * c, r_out * s, -h)), xf((r_out * c, r_out * s, h))
        pi_lo, pi_hi = xf((r_in * c, r_in * s, -h)), xf((r_in * c, r_in * s, h))
        cols["out_lo"].append(o.vert(po_lo, (u, 0.0), radial))
        cols["out_hi"].append(o.vert(po_hi, (u, 1.0), radial))
        cols["in_lo"].append(o.vert(pi_lo, (u, 0.0), inward))
        cols["in_hi"].append(o.vert(pi_hi, (u, 1.0), inward))
        # Edges: plain film base (V = 0.5 sits between the sprocket rows and the frame, so it reads as film body).
        cols["el_lo"].append(o.vert(po_lo, (u, 0.19), down))
        cols["el_hi"].append(o.vert(pi_lo, (u, 0.19), down))
        cols["eh_lo"].append(o.vert(po_hi, (u, 0.19), up))
        cols["eh_hi"].append(o.vert(pi_hi, (u, 0.19), up))
    for i in range(segs):
        j = i + 1
        o.quad(cols["out_lo"][i], cols["out_lo"][j], cols["out_hi"][j], cols["out_hi"][i])
        o.quad(cols["in_lo"][i], cols["in_hi"][i], cols["in_hi"][j], cols["in_lo"][j])
        o.quad(cols["el_lo"][i], cols["el_hi"][i], cols["el_hi"][j], cols["el_lo"][j])
        o.quad(cols["eh_lo"][i], cols["eh_lo"][j], cols["eh_hi"][j], cols["eh_hi"][i])


def build_sparkle(o, centre, phase):
    # An octahedron (8 faceted triangles) with its own normals per face.
    s = SPARKLE_SIZE
    cx, cy, cz = centre
    pts = [(s, 0, 0), (-s, 0, 0), (0, s, 0), (0, -s, 0), (0, 0, s * 1.8), (0, 0, -s * 1.8)]
    faces = [(0, 2, 4), (2, 1, 4), (1, 3, 4), (3, 0, 4), (2, 0, 5), (1, 2, 5), (3, 1, 5), (0, 3, 5)]
    for a, b, c in faces:
        pa, pb, pc = pts[a], pts[b], pts[c]
        ux, uy, uz = pb[0] - pa[0], pb[1] - pa[1], pb[2] - pa[2]
        vx, vy, vz = pc[0] - pa[0], pc[1] - pa[1], pc[2] - pa[2]
        n = (uy * vz - uz * vy, uz * vx - ux * vz, ux * vy - uy * vx)
        ln = math.sqrt(sum(k * k for k in n)) or 1.0
        n = tuple(k / ln for k in n)
        ids = [o.vert((p[0] + cx, p[1] + cy, p[2] + cz), (30.0 + phase, 0.5), n) for p in (pa, pb, pc)]
        o.tri(*ids)


def write_obj():
    o = Obj()
    build_core(o)
    for radius, width, axis, deg, direction in BELTS:
        build_belt(o, radius, width, axis, deg, direction)
    for centre, phase in SPARKLES:
        build_sparkle(o, centre, phase)
    o.write(OBJ_PATH)
    log("wrote %s: %d corners, %d triangles" % (OBJ_PATH, len(o.v), len(o.f)))


def import_mesh():
    ui = unreal.FbxImportUI()
    ui.set_editor_property("import_mesh", True)
    ui.set_editor_property("import_as_skeletal", False)
    ui.set_editor_property("import_animations", False)
    ui.set_editor_property("import_materials", False)
    ui.set_editor_property("import_textures", False)
    ui.set_editor_property("mesh_type_to_import", unreal.FBXImportType.FBXIT_STATIC_MESH)
    data = ui.get_editor_property("static_mesh_import_data")
    data.set_editor_property("combine_meshes", True)
    data.set_editor_property("auto_generate_collision", False)
    data.set_editor_property("generate_lightmap_u_vs", True)
    data.set_editor_property("normal_import_method", unreal.FBXNormalImportMethod.FBXNIM_IMPORT_NORMALS)
    task = unreal.AssetImportTask()
    task.set_editor_property("filename", OBJ_PATH)
    task.set_editor_property("destination_path", ART)
    task.set_editor_property("destination_name", MESH_NAME)
    task.set_editor_property("automated", True)
    task.set_editor_property("replace_existing", True)
    task.set_editor_property("save", False)
    task.set_editor_property("options", ui)
    tools.import_asset_tasks([task])
    mesh = eal.load_asset(ART + "/" + MESH_NAME)
    if not mesh:
        err("mesh import failed")
        return None
    sme = unreal.get_editor_subsystem(unreal.StaticMeshEditorSubsystem)
    sme.remove_collisions(mesh)  # VisualMesh has collision off; CollisionSphere does the gameplay collision
    box = mesh.get_bounding_box()
    log("%s bounds min %s max %s" % (MESH_NAME, box.min, box.max))
    return mesh


